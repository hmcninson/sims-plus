@router.post(
    "/reports/fee-collection",
    summary="Generate fee collection report PDF",
    dependencies=[Depends(require_permissions("finance.reports"))],
    responses={200: {"content": {"application/pdf": {}}}},
)
async def generate_fee_collection_report(
    request: FinancialReportRequest,
    tenant: RequestTenant,
    user: ValidatedUser,
    db: DatabaseSession,
) -> StreamingResponse:
    """
    Generate a fee collection report as PDF.

    Shows payment totals broken down by fee type for the given academic year,
    term, class, and date range filters. Requires `finance.reports` permission.
    """
    service = FinanceReportService(db)

    try:
        data = await service.get_fee_collection_data(
            tenant_id=tenant.tenant_id,
            academic_year_id=request.academic_year_id,
            term_id=request.term_id,
            class_id=request.class_id,
            date_from=request.date_from,
            date_to=request.date_to,
        )
    except FinanceReportError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=e.message,
        )

    # Build table data from fee type breakdown
    headers = ["Fee Type", "Payments", "Total Collected"]
    rows = [
        [
            item["fee_type"],
            str(item["payment_count"]),
            f"{item['total_collected']:,.2f}",
        ]
        for item in data["fee_type_breakdown"]
    ]

    summary = {
        "Total Payments": str(data["total_payments"]),
        "Grand Total Collected": f"{data['grand_total']:,.2f}",
    }

    pdf_bytes = await _generate_simple_pdf(
        title="Fee Collection Report",
        headers=headers,
        rows=rows,
        summary=summary,
    )

    return StreamingResponse(
        BytesIO(pdf_bytes),
        media_type="application/pdf",
        headers={
            "Content-Disposition": "attachment; filename=fee-collection-report.pdf",
        },
    )


@router.post(
    "/reports/outstanding-fees",
    summary="Generate outstanding fees report PDF",
    dependencies=[Depends(require_permissions("finance.reports"))],
    responses={200: {"content": {"application/pdf": {}}}},
)
async def generate_outstanding_fees_report(
    request: FinancialReportRequest,
    tenant: RequestTenant,
    user: ValidatedUser,
    db: DatabaseSession,
) -> StreamingResponse:
    """
    Generate an outstanding fees report as PDF.

    Lists students with unpaid invoice balances for the given academic year
    and optional term/class filters. Requires `finance.reports` permission.
    """
    service = FinanceReportService(db)

    try:
        data = await service.get_outstanding_fees_data(
            tenant_id=tenant.tenant_id,
            academic_year_id=request.academic_year_id,
            term_id=request.term_id,
            class_id=request.class_id,
        )
    except FinanceReportError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=e.message,
        )

    # Build table data from students with outstanding balances
    headers = ["Student ID", "Name", "Class", "Total Invoiced", "Total Paid", "Balance Due"]
    rows = [
        [
            s["student_number"] or "N/A",
            s["name"],
            s["class_name"],
            f"{s['total_invoiced']:,.2f}",
            f"{s['total_paid']:,.2f}",
            f"{s['balance_due']:,.2f}",
        ]
        for s in data["students"]
    ]

    summary = {
        "Total Students with Outstanding Balances": str(data["total_students"]),
        "Total Outstanding Amount": f"{data['total_outstanding']:,.2f}",
    }

    pdf_bytes = await _generate_simple_pdf(
        title="Outstanding Fees Report",
        headers=headers,
        rows=rows,
        summary=summary,
    )

    return StreamingResponse(
        BytesIO(pdf_bytes),
        media_type="application/pdf",
        headers={
            "Content-Disposition": "attachment; filename=outstanding-fees-report.pdf",
        },
    )


