async def _generate_simple_pdf(
    title: str,
    headers: list[str],
    rows: list[list],
    summary: dict | None = None,
) -> bytes:
    """
    Generate a simple tabular PDF report using WeasyPrint.

    This is a lightweight helper for financial reports that don't yet
    have a dedicated branded template. Uses a clean table layout with
    SIMS Plus styling.
    """
    from weasyprint import HTML

    header_html = "".join(f"<th>{h}</th>" for h in headers)

    rows_html = ""
    for row in rows:
        cells = "".join(f"<td>{cell}</td>" for cell in row)
        rows_html += f"<tr>{cells}</tr>"

    summary_html = ""
    if summary:
        for key, value in summary.items():
            summary_html += f"<p><strong>{key}:</strong> {value}</p>"

    html_content = f"""
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">
        <style>
            body {{ font-family: Arial, sans-serif; margin: 40px; color: #333; }}
            h1 {{ color: #1B4F72; border-bottom: 2px solid #1B4F72; padding-bottom: 10px; }}
            table {{ width: 100%; border-collapse: collapse; margin: 20px 0; }}
            th {{ background-color: #1B4F72; color: white; padding: 10px; text-align: left; }}
            td {{ padding: 8px 10px; border-bottom: 1px solid #ddd; }}
            tr:nth-child(even) {{ background-color: #f9fafb; }}
            .summary {{ background-color: #f0f4f8; padding: 15px; border-radius: 8px; margin-top: 20px; }}
            .generated {{ color: #666; font-size: 12px; margin-top: 30px; }}
        </style>
    </head>
    <body>
        <h1>{title}</h1>
        <table>
            <thead><tr>{header_html}</tr></thead>
            <tbody>{rows_html}</tbody>
        </table>
        <div class="summary">{summary_html}</div>
        <p class="generated">Generated by SIMS Plus on {datetime.now().strftime("%d/%m/%Y %H:%M")}</p>
    </body>
    </html>
    """

    pdf_bytes = HTML(string=html_content).write_pdf()
    return pdf_bytes


