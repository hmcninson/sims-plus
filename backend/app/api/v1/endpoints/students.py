@guardians_router.delete(
    "/{guardian_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    summary="Delete guardian",
    dependencies=[Depends(require_permissions("students.delete"))],
)
async def delete_guardian(
    guardian_id: UUID,
    tenant: RequestTenant,
    db: DatabaseSession,
) -> None:
    """Soft delete a guardian."""
    service = StudentService(db)
    try:
        deleted = await service.delete_guardian(guardian_id)

        if not deleted:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Guardian not found",
            )
    except StudentServiceError as e:
        if e.code == "guardian_has_linked_students":
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=str(e),
            )
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )


@guardians_router.get(
    "/{guardian_id}/students",
    response_model=list[StudentListResponse],
    summary="Get guardian's students",
    dependencies=[Depends(require_permissions("students.read"))],
)
async def get_guardian_students(
    guardian_id: UUID,
    tenant: RequestTenant,
    db: DatabaseSession,
) -> list[StudentListResponse]:
    """Get all students linked to a guardian."""
    service = StudentService(db)
    links = await service.get_guardian_students(tenant.tenant_id, guardian_id)

    return [
        StudentListResponse(
            id=link.student_rel.id,
            student_id=link.student_rel.student_id,
            previous_student_id=link.student_rel.previous_student_id,
            first_name=link.student_rel.first_name,
            middle_name=link.student_rel.middle_name,
            last_name=link.student_rel.last_name,
            gender=link.student_rel.gender.value,
            date_of_birth=link.student_rel.date_of_birth,
            status=link.student_rel.status.value,
            class_id=link.student_rel.class_id,
            class_name=None,  # Would need to load class relationship
            section_id=link.student_rel.section_id,
            section_name=None,  # Would need to load section relationship
            photo_url=link.student_rel.photo_url,
        )
        for link in links
    ]
