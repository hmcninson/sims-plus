# Allowed MIME types for import files
ALLOWED_IMPORT_TYPES = {
    "text/csv": "csv",
    "application/vnd.ms-excel": "xls",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": "xlsx",
}

# Max file size: 5MB
MAX_IMPORT_SIZE = 5 * 1024 * 1024


@router.post(
    "/import",
    response_model=StudentImportResponse,
    summary="Import students from CSV/Excel",
    description="Import students from a CSV or Excel file. Supports preview mode to validate data before importing.",
    dependencies=[Depends(require_permissions("students.create"))],
)
async def import_students(
    tenant: RequestTenant,
    db: DatabaseSession,
    file: UploadFile = File(..., description="CSV or Excel file with student data"),
    preview: bool = Form(default=False, description="If true, only preview without creating"),
    auto_generate_ids: bool = Form(default=True, description="Auto-generate student IDs for missing ones"),
) -> StudentImportResponse:
    """
    Import students from a CSV or Excel file.

    The file should have a header row with column names. Columns are auto-mapped to student fields.

    Supported columns:
    - student_id (or: student_no, id, admission_no)
    - first_name (or: firstname, first, given_name)
    - middle_name (or: middlename, middle)
    - last_name (or: lastname, surname, family_name)
    - date_of_birth (or: dob, birth_date) - formats: YYYY-MM-DD, DD/MM/YYYY, etc.
    - gender (or: sex) - values: M/F, Male/Female, Boy/Girl
    - email
    - phone (or: mobile, telephone)
    - address
    - city
    - region
    - is_boarder (or: boarder) - values: Yes/No, True/False, 1/0

    Returns preview data in preview mode, or import results in import mode.
    """
    # Validate file type
    content_type = file.content_type or ""
    if content_type not in ALLOWED_IMPORT_TYPES:
        # Try to detect from filename
        filename = file.filename or ""
        if filename.lower().endswith(".csv"):
            file_type = "csv"
        elif filename.lower().endswith(".xlsx"):
            file_type = "xlsx"
        elif filename.lower().endswith(".xls"):
            file_type = "xls"
        else:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid file type. Allowed: CSV, XLS, XLSX. Got: {content_type}",
            )
    else:
        file_type = ALLOWED_IMPORT_TYPES[content_type]

    # Read file content
    content = await file.read()

    # Validate file size
    if len(content) > MAX_IMPORT_SIZE:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"File too large. Maximum size is 5MB. Got: {len(content) / 1024 / 1024:.2f}MB",
        )

    # Validate file is not empty
    if len(content) == 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="File is empty",
        )

    # Import students
    service = StudentService(db)
    try:
        result = await service.import_students_from_file(
            tenant_id=tenant.tenant_id,
            file_content=content,
            file_type=file_type,
            preview_only=preview,
            auto_generate_ids=auto_generate_ids,
        )
        return StudentImportResponse(**result)
    except StudentServiceError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=e.message,
        )


